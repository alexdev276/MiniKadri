import configparser

from firebird.driver import create_database, connect, driver_config, types
from contextlib import closing

def configure_db():
    driver_config.register_server("local", """
    [local]
    host = localhost
    """)
    driver_config.register_database("minikadri", """
    [minikadri]
    server = local
    protocol = inet
    database = /db/minikadri.fdb
    charset = UTF8
    db_charset = UTF8
    """)

def schema(connection):
    statements = (
        """create table settings (
            settings_key varchar(100) ,
            settings_value varchar(255) not null
        )""",
        """create table position_groups (
                    id integer generated by default as identity,
                    name varchar(100) not null,
                    constraint pk_position_groups primary key (id)
                )""",
        """create table positions (
            id integer generated by default as identity,
            group_id integer not null,
            name varchar(150) not null,
            constraint pk_positions primary key (id),
            constraint fk_positions foreign key (group_id) references position_groups(id)
        )""",
        """create table employees (
            id integer generated by default as identity,
            last_name varchar(100) not null,
            first_name varchar(100) not null,
            middle_name varchar(100),
            birth_date date not null,
            position_id integer not null,
            photo blob sub_type binary,
            note blob sub_type text,
            constraint pk_employees primary key (id),
            constraint fk_employees foreign key (position_id) references positions(id)
        )""",
        """create table military (
            employee_id integer generated by default as identity,
            is_registered smallint default 0 not null,
            category varchar(50),
            rank varchar(100),
            vus varchar(50),
            office varchar(255),
            constraint pk_military primary key (employee_id),
            constraint fk_military foreign key (employee_id) references employees(id)
        )""",
        """create table languages (
            id integer generated by default as identity,
            name varchar(100) not null,
            constraint pk_languages primary key (id)
        )""",
        """create table employee_languages (
            employee_id integer generated by default as identity,
            language_id integer generated by default as identity,
            constraint pk_languages_employee primary key (employee_id, language_id),
            constraint fk_languages_language foreign key (language_id) references languages(id),
            constraint fk_languages_employee foreign key (employee_id) references employees(id)
        )""",
        """create table education (
            id integer generated by default as identity,
            employee_id integer not null,
            institution varchar(100) not null,
            speciality varchar(255) not null,
            year_end smallint not null,
            constraint pk_education primary key (id),
            constraint fk_education foreign key (employee_id) references employees(id)
        )""",
        """create table order_types (
            id integer generated by default as identity,
            code varchar(50) not null,
            name varchar(150) not null,
            constraint pk_order_types primary key (id)
        )""",
        """create table order_templates (
            id integer generated by default as identity,
            order_type_id integer not null,
            name varchar(200) not null,
            template_markdown blob sub_type text not null,
            created_at timestamp,
            constraint pk_order_templates primary key (id),
            constraint fk_order foreign key (order_type_id) references order_types(id)
        )""",
         """create table orders (
            id integer generated by default as identity,
            order_type_id integer not null,
            employee_id integer not null,
            number varchar(500),
            order_date date not null,
            date_from date not null,
            date_to date not null,
            title varchar(255) not null,
            note blob sub_type text not null,
            content_markdown blob sub_type text not null,
            constraint pk_orders primary key (id),
            constraint fk_orders_order foreign key (order_type_id) references order_types(id),
            constraint fk_orders_employee foreign key (employee_id) references employees(id)
        )""",
        """create table employee_passports (
            id integer generated by default as identity,
            employee_id integer not null,
            series varchar(10) not null,
            number varchar(20) not null,
            issued_by varchar(255) not null,
            issue_date date not null,
            department_code varchar(20) not null,
            registration_adress varchar(500) not null,
            verified smallint not null,
            verified_at timestamp not null,
            verified_by integer not null,
            constraint pk_employees_passports primary key (id),
            constraint fk_employee_passports_emp foreign key (employee_id) references employees(id),
            constraint fk_employee_passports_ver foreign key (verified_by) references employees(id)
        )""",
        """create table day_statuses (
            id integer generated by default as identity,
            code varchar(30) not null,
            name varchar(100) not null,
            color varchar(20) not null,
            is_working smallint not null,
            constraint pk_day_statuses primary key (id)
        )""",
        """create table timesheet (
            id integer generated by default as identity,
            employee_id integer not null,
            work_date date not null,
            status_id integer not null,
            hours_worked numeric(5, 2) not null,
            constraint pk_timesheet primary key (id),
            constraint fk_timesheet_emp foreign key (employee_id) references employees(id),
            constraint fk_timesheet_status foreign key (status_id) references day_statuses(id)
        )""",
        """create table employee_documents (
            id integer generated by default as identity,
            employee_id integer not null,
            document_type varchar(100) not null,
            file_name varchar(255) not null,
            file_path varchar(500) not null,
            issue_date date not null,
            expiry_date date not null,
            note blob sub_type text not null,
            created_at timestamp,
            constraint pk_employee_documents primary key (id),
            constraint fk_employee_documents foreign key (employee_id) references employees(id)
        )"""
    )
    with connection.cursor() as cursor:
        for s in statements:
            cursor.execute(s)
    connection.commit()

